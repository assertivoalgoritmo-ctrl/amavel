import 'package:amavel_app/domain/models/alert.dart';
import 'package:amavel_app/data/repositories/alert_repository.dart';
import 'package:amavel_app/services/safety/distress_detector.dart';

/// Alert notification timing strategy
enum NotificationStrategy {
  immediate, // Send immediately (critical)
  withinHour, // Send within 1 hour (high)
  daily, // Aggregate in daily report (medium)
  weekly, // Aggregate in weekly report (low/info)
}

/// Creates alerts in Firestore and triggers notifications
class AlertDispatcher {
  final AlertRepository _repository;
  final Map<String, DateTime> _lastDispatchTimes = {};

  AlertDispatcher(this._repository);

  /// Dispatches an alert based on severity
  Future<String?> dispatchAlert(
    Alert alert, {
    DetectedDistress? distress,
  }) async {
    try {
      // Store alert in Firestore
      final alertId = await _repository.createAlert(
        userId: alert.userId,
        severity: alert.severity,
        title: alert.title,
        description: alert.description,
        detectedPatterns: alert.detectedPatterns,
        metadata: alert.metadata,
      );

      // Determine notification strategy based on severity
      final strategy = _getNotificationStrategy(alert.severity);

      // Trigger notification based on strategy
      await _triggerNotification(
        alertId,
        alert,
        strategy,
        distress,
      );

      // Log dispatch
      _lastDispatchTimes[alertId] = DateTime.now();

      return alertId;
    } catch (e) {
      print('Erro ao enviar alerta: $e');
      return null;
    }
  }

  /// Gets notification strategy for severity level
  NotificationStrategy _getNotificationStrategy(AlertSeverity severity) {
    switch (severity) {
      case AlertSeverity.critical:
        return NotificationStrategy.immediate;
      case AlertSeverity.high:
        return NotificationStrategy.withinHour;
      case AlertSeverity.medium:
        return NotificationStrategy.daily;
      case AlertSeverity.low:
        return NotificationStrategy.weekly;
    }
  }

  /// Triggers notification based on strategy
  Future<void> _triggerNotification(
    String alertId,
    Alert alert,
    NotificationStrategy strategy,
    DetectedDistress? distress,
  ) async {
    switch (strategy) {
      case NotificationStrategy.immediate:
        await _sendImmediateNotification(alert, distress);
        break;
      case NotificationStrategy.withinHour:
        await _scheduleNotification(alert, Duration(minutes: 5));
        break;
      case NotificationStrategy.daily:
        await _scheduleNotification(alert, Duration(hours: 24));
        break;
      case NotificationStrategy.weekly:
        await _scheduleNotification(alert, Duration(days: 7));
        break;
    }
  }

  /// Sends an immediate notification (critical alerts)
  Future<void> _sendImmediateNotification(
    Alert alert,
    DetectedDistress? distress,
